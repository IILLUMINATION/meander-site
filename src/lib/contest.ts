// Живые события главной. Дата задана здесь, а не внутри компонента: страница
// статическая и обновляется по ISR раз в 30 минут, поэтому решение «показывать
// конкурс или нет» принимает сервер и отдаёт клиенту как prop. Иначе серверная
// разметка и гидрация разошлись бы ровно в дедлайн.
export const CONTEST_ENDS_AT = new Date("2026-12-31T23:59:59+03:00");

/** Идёт ли конкурс квестов прямо сейчас. */
export function isContestActive(now: number = Date.now()): boolean {
  return now <= CONTEST_ENDS_AT.getTime();
}
